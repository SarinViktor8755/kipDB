    /** Семейство датчиков с согласованными характеристиками */
    private static final class SensorFamily {
        final String[] sensorTypes;
        final String unit;
        final String[] scaleMins;
        final String[] scaleMaxs;
        final String category;
        final String mpi;
        final String[] accuracyClasses;
        final String[] redLines;   // может содержать null-подобные значения ""

        SensorFamily(String[] sensorTypes, String unit,
                     String[] scaleMins, String[] scaleMaxs,
                     String category, String mpi,
                     String[] accuracyClasses, String[] redLines) {
            this.sensorTypes = sensorTypes;
            this.unit = unit;
            this.scaleMins = scaleMins;
            this.scaleMaxs = scaleMaxs;
            this.category = category;
            this.mpi = mpi;
            this.accuracyClasses = accuracyClasses;
            this.redLines = redLines;
        }

        String pickSensorType()      { return pick(sensorTypes); }
        String pickScaleMin()        { return pick(scaleMins); }
        String pickScaleMax()        { return pick(scaleMaxs); }
        String pickAccuracyClass()   { return pick(accuracyClasses); }
        String pickRedLine()         { return pick(redLines); }
    }

    private static String pick(String[] arr) {
        if (arr == null || arr.length == 0) return "";
        return arr[RANDOM.nextInt(arr.length)];
    }

