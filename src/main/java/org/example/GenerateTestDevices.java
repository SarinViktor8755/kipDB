    public static void main(String[] args) {
        System.out.println("====================================");
        System.out.println(" Генерация тестовых приборов");
        System.out.println(" (на основе реальных данных)");
        System.out.println("====================================");

        try {
            Db.init();
            System.out.println("Используемая БД: " + Db.getDatabasePath());

            try (Connection connection = Db.openConnection()) {
                connection.setAutoCommit(false);
                try {
                    Set<String> usedNumbers = loadExistingSerialNumbers(connection);
                    System.out.println("Уже занято номеров: " + usedNumbers.size());

                    String sql = """
                        INSERT INTO devices (
                            serial_number, name, location, last_verification,
                            next_verification, photo_path, photo_thumb_path,
                            is_deleted, version, created_at, details_json
                        ) VALUES (?, ?, ?, ?, ?, NULL, NULL, 0, 1, ?, ?)
                        """;

                    LocalDate today = LocalDate.now();

                    try (PreparedStatement ps = connection.prepareStatement(sql)) {
                        for (int i = 1; i <= DEVICES_COUNT; i++) {
                            String serial = generateUniqueSerial(usedNumbers);
                            GeneratedDevice g = generateDevice(i, today);

                            ps.setString(1, serial);
                            ps.setString(2, g.name);
                            ps.setString(3, g.location);
                            ps.setString(4, g.lastVerification);
                            ps.setString(5, g.nextVerification);
                            ps.setString(6, LocalDateTime.now().format(DB_DATE_FORMAT));
                            ps.setString(7, g.detailsJson);
                            ps.addBatch();

                            if (i % 500 == 0) {
                                ps.executeBatch();
                                System.out.println("Добавлено: " + i + " / " + DEVICES_COUNT);
                            }
                        }
                        ps.executeBatch();
                    }

                    connection.commit();
                    System.out.println();
                    System.out.println("====================================");
                    System.out.println(" ГОТОВО! Добавлено приборов: " + DEVICES_COUNT);
                    System.out.println("====================================");
                } catch (Exception e) {
                    connection.rollback();
                    System.err.println("Ошибка! Изменения отменены.");
                    throw e;
                } finally {
                    connection.setAutoCommit(true);
                }
            }
        } catch (Exception e) {
            System.err.println("Ошибка генерации тестовых данных:");
            e.printStackTrace();
        }
    }

    /** Загрузка уже существующих зав. номеров */
    private static Set<String> loadExistingSerialNumbers(Connection c) throws SQLException {
        Set<String> used = new HashSet<>();
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery("SELECT serial_number FROM devices")) {
            while (rs.next()) {
                String n = rs.getString(1);
                if (n != null && !n.isBlank()) used.add(n);
            }
        }
        return used;
    }

    /** Генерация уникального номера */
    private static String generateUniqueSerial(Set<String> used) {
        String serial;
        do {
            serial = String.valueOf(100000 + RANDOM.nextInt(900000));
        } while (!used.add(serial));
        return serial;
    }

    /** Сгенерированный прибор */
    private static final class GeneratedDevice {
        String name, location, lastVerification, nextVerification, detailsJson;
    }

    /**
     * Генерирует один прибор, комбинируя данные из «сырья»:
     * случайное семейство → случайные датчик/шкала/класс → случайные даты и группа/позиция.
     */
    private static GeneratedDevice generateDevice(int index, LocalDate today) {
        GeneratedDevice g = new GeneratedDevice();

        SensorFamily family = pickFamily();

        // Позиция и группа (из реальных данных)
        String positionName = pick(POSITION_NAMES);
        String groupName = pick(GROUP_NAMES);

        // Если позиция пустая — используем «Осциллограф»-подобное название
        if (positionName == null || positionName.isBlank()) {
            positionName = "Позиция " + index;
        }

        // Наименование — позиция + индекс для уникальности
        g.name = positionName + " (" + String.format("%04d", index) + ")";

        // Местоположение = группа (или Склад, Резерв)
        g.location = groupName.isBlank() ? "Склад" : groupName;

        // Даты поверки
        g.lastVerification = today.minusDays(30 + RANDOM.nextInt(670)).toString();
        LocalDate next = LocalDate.parse(g.lastVerification)
                .plusDays(365 + RANDOM.nextInt(61) - 30);
        g.nextVerification = next.toString();

        // JSON с деталями (те самые поля, что во фронте)
        org.json.JSONObject details = new org.json.JSONObject();
        details.put("sensorType", family.pickSensorType());
        details.put("unit", family.unit);
        details.put("scaleMin", family.pickScaleMin());
        details.put("scaleMax", family.pickScaleMax());
        details.put("category", family.category);
        details.put("mpi", family.mpi);
        details.put("accuracyClass", family.pickAccuracyClass());
        details.put("redLine", family.pickRedLine());
        details.put("writeOff", "");
        details.put("deferredVerification", "");
        details.put("movement", "");
        details.put("rowNumber", String.valueOf(index));
        details.put("groupName", groupName);
        details.put("positionName", positionName);

        g.detailsJson = details.toString();
        return g;
    }

    /** Случайный выбор семейства из всех массивов */
    private static SensorFamily pickFamily() {
        int r = RANDOM.nextInt(100);
        if (r < 60)  return pick(PRESSURE_FAMILIES);
        if (r < 75)  return pick(MPA_FAMILIES);
        if (r < 85)  return pick(DIFF_PRESSURE_FAMILIES);
        if (r < 95)  return pick(TEMP_FAMILIES);
        return pick(OTHER_FAMILIES);
    }

    private static <T> T pick(T[] arr) {
        return arr[RANDOM.nextInt(arr.length)];
    }
